/**
 * 브리핑 항목. 문장 단위로 들고 있어야 끊긴 문장을 처음부터 다시 읽고, 분량을 문장 경계에서 줄일 수 있다.
 * 실제 서비스에서는 일정·메일·구독 뉴스를 요약 모델이 이 형태(헤드라인 1문장 + 본문 문장들)로 만든다.
 */
data class BriefItem(
    val id: String,
    val title: String,
    /** 1(낮음)∼5(높음). 사용자가 고른 관심도 + 마감·일정 임박도. */
    val priority: Int,
    val sentences: List<String>,
) {
    init {
        require(sentences.isNotEmpty()) { "$id: 문장이 없다" }
        require(priority in 1..5) { "$id: 우선순위 범위 밖" }
    }
}

/** 한 항목을 얼마나 읽을지. 헤드라인=첫 문장, 요약=앞쪽 절반, 전체=모든 문장. */
enum class Depth(val weight: Double) {
    SKIP(0.0), HEADLINE(0.5), SUMMARY(0.8), FULL(1.0);

    fun sentenceCount(total: Int): Int = when (this) {
        SKIP -> 0
        HEADLINE -> 1
        SUMMARY -> maxOf(1, (total + 1) / 2)
        FULL -> total
    }

    fun next(): Depth? = entries.getOrNull(ordinal + 1)
}

